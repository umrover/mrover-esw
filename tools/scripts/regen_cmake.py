import argparse
import re
import sys
from pathlib import Path

from esw import esw_logger
from esw.cubemx.cmake import configure_cmake

ROOT = Path(__file__).resolve().parents[2]
CTX = ROOT / "lib" / "stm32g4"
MARKER = "AUTO-GENERATED BY update_cmake_cfg.py"

_LIBS_RE = re.compile(r"# Add user defined libraries\n(.*?)\)", re.DOTALL)
_RTOS_RE = re.compile(r'option\(MROVER_USE_RTOS ".*" ON\)')
_CCMSRAM_RE = re.compile(r"set\(MX_USE_CCMSRAM ON\)")


def find_projects() -> list[Path]:
    found = []
    for top in ("src", "starter-projects"):
        for cmakelists in (ROOT / top).rglob("CMakeLists.txt"):
            if "build" in cmakelists.relative_to(ROOT).parts:
                continue
            if MARKER in cmakelists.read_text():
                found.append(cmakelists.parent)
    return sorted(found)


def read_settings(cmakelists: Path) -> tuple[list[str], bool, bool]:
    text = cmakelists.read_text()
    if "<<<<<<<" in text:
        raise RuntimeError(f"{cmakelists} has unresolved merge conflicts")
    match = _LIBS_RE.search(text)
    if not match:
        raise RuntimeError(f"no '# Add user defined libraries' block in {cmakelists}")
    libs = [line.strip() for line in match.group(1).splitlines() if line.strip() and not line.strip().startswith("#")]
    return libs, bool(_RTOS_RE.search(text)), bool(_CCMSRAM_RE.search(text))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="re-generate all project CMakeLists from the templates")
    parser.add_argument("projects", nargs="*", type=Path, help="project directories (default to all)")
    args = parser.parse_args()

    projects = [p.resolve() for p in args.projects] or find_projects()
    failed = []
    for project in projects:
        try:
            # read everything before configure_cmake deletes the old files
            libs, rtos, ccmsram = read_settings(project / "CMakeLists.txt")
            esw_logger.info(f"{project.relative_to(ROOT)}: libs={libs} rtos={rtos} ccmsram={ccmsram}")
            configure_cmake(project.name, project, ROOT, CTX, libs, rtos, ccmsram)
        except Exception as e:
            esw_logger.error(f"{project}: {e}")
            failed.append(project)

    if failed:
        esw_logger.error(f"failed: {[str(p.relative_to(ROOT)) for p in failed]}")
        sys.exit(1)
