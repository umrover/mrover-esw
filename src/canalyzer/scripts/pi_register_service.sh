#!/bin/bash
# Registers canalyzer.service with systemd so the CANalyzer stack (CAN
# bring-up, influxdb, grafana, can logger) starts on boot once the CAN
# interfaces exist. Run on the pi; it asks for sudo when it needs it.
#
# usage: ./pi_register_service.sh [options] [can_iface ...]
#   can_iface    CAN interfaces to wait for at boot
#                (default: the buses in canalyzer_config.yaml)
#   --print      show the unit that would be installed, change nothing
#   --no-start   enable for the next boot without (re)starting it now
#   --remove     stop, disable and delete the service
#
# Rerun after editing canalyzer.service or the buses in canalyzer_config.yaml.
set -euo pipefail

SERVICE_NAME="canalyzer.service"
UNIT_PATH="/etc/systemd/system/$SERVICE_NAME"

SCRIPT_PATH="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")"
SCRIPT_DIR="$(dirname "$SCRIPT_PATH")"
CANALYZER_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
TEMPLATE="$SCRIPT_DIR/$SERVICE_NAME"
CONFIG="$CANALYZER_DIR/canalyzer_config.yaml"

# prints the comment block at the top of this file
usage() { awk 'NR == 1 { next } /^#/ { sub(/^# ?/, ""); print; next } { exit }' "$0"; }
die() {
    echo "Error: $*" >&2
    exit 1
}

ORIGINAL_ARGS=("$@")
PRINT_ONLY=0
START=1
REMOVE=0
IFACES=()
while [ $# -gt 0 ]; do
    case "$1" in
        --print) PRINT_ONLY=1 ;;
        --no-start) START=0 ;;
        --remove) REMOVE=1 ;;
        -h | --help)
            usage
            exit 0
            ;;
        -*) die "unknown option '$1'" ;;
        *) IFACES+=("$1") ;;
    esac
    shift
done

command -v systemctl >/dev/null || die "systemctl not found; this needs a systemd machine"

if [ "$PRINT_ONLY" -eq 0 ] && [ "$EUID" -ne 0 ]; then
    echo ">> Re-running with sudo..."
    exec sudo "$SCRIPT_PATH" "${ORIGINAL_ARGS[@]}"
fi

# --------------------------------------------------------------------------
# --remove
# --------------------------------------------------------------------------
if [ "$REMOVE" -eq 1 ]; then
    if [ ! -f "$UNIT_PATH" ]; then
        echo "$SERVICE_NAME is not installed."
        exit 0
    fi
    echo ">> Stopping and disabling $SERVICE_NAME (this runs pi_stop.sh)..."
    systemctl disable --now "$SERVICE_NAME" || true
    rm -f "$UNIT_PATH"
    systemctl daemon-reload
    echo ">> Removed $SERVICE_NAME"
    exit 0
fi

# --------------------------------------------------------------------------
# work out what goes in the unit
# --------------------------------------------------------------------------
[ -f "$TEMPLATE" ] || die "unit template not found at $TEMPLATE"
for script in restart_can.sh pi_start.sh pi_stop.sh; do
    [ -x "$SCRIPT_DIR/$script" ] || die "$SCRIPT_DIR/$script is missing or not executable"
done
# the path goes into ExecStart= unquoted and through sed, so keep it plain
[[ "$CANALYZER_DIR" =~ ^[A-Za-z0-9_./-]+$ ]] || die "repo path '$CANALYZER_DIR' has characters systemd can't take unquoted; move the repo"

if [ "${#IFACES[@]}" -eq 0 ]; then
    [ -f "$CONFIG" ] || die "no interfaces given and $CONFIG not found"
    # the logger only uses the first logger_bus_size entries under loggers:
    bus_count="$(sed -n 's/^logger_bus_size:[[:space:]]*\([0-9][0-9]*\).*/\1/p' "$CONFIG")"
    mapfile -t IFACES < <(sed -n 's/^[[:space:]]*-[[:space:]]*name:[[:space:]]*\([^[:space:]#]*\).*/\1/p' "$CONFIG")
    [ -n "$bus_count" ] && IFACES=("${IFACES[@]:0:$bus_count}")
    [ "${#IFACES[@]}" -gt 0 ] || die "no buses found in $CONFIG; pass the interfaces as arguments"
fi

DEVICES=()
MISSING=()
for iface in "${IFACES[@]}"; do
    # device unit names escape anything else, keep it simple
    [[ "$iface" =~ ^[A-Za-z0-9_]+$ ]] || die "unsupported interface name '$iface'"
    DEVICES+=("sys-subsystem-net-devices-$iface.device")
    [ -e "/sys/class/net/$iface" ] || MISSING+=("$iface")
done

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT
RENDERED="$WORK_DIR/$SERVICE_NAME"
{
    echo "# Generated by $SCRIPT_PATH"
    echo "# from $TEMPLATE. Edit that file and rerun the script instead of editing this one."
    # drop the template's own header comment, fill in the placeholders
    sed -e '1,/^\[Unit\]/{/^#/d}' \
        -e "s#@CANALYZER_DIR@#$CANALYZER_DIR#g" \
        -e "s#@CAN_DEVICES@#${DEVICES[*]}#g" \
        "$TEMPLATE"
} >"$RENDERED"
if grep -q '@[A-Z_]*@' "$RENDERED"; then
    die "unfilled placeholder in the unit: $(grep -o '@[A-Z_]*@' "$RENDERED" | sort -u | tr '\n' ' ')"
fi

echo ">> Waiting at boot for: ${IFACES[*]}"
if [ "${#MISSING[@]}" -gt 0 ]; then
    echo "   Warning: ${MISSING[*]} not present right now. At boot the service waits up to"
    echo "   90s for missing interfaces, then starts anyway. If this pi doesn't have them,"
    echo "   rerun with only the interfaces it has, e.g.: $0 can0 can1"
fi

if [ "$PRINT_ONLY" -eq 1 ]; then
    echo ">> Unit that would be installed at $UNIT_PATH:"
    echo
    cat "$RENDERED"
    exit 0
fi

# --------------------------------------------------------------------------
# install and enable
# --------------------------------------------------------------------------
systemctl cat docker.service >/dev/null 2>&1 || die "docker.service not found; install docker first"

if ! verify_out="$(systemd-analyze verify "$RENDERED" 2>&1)"; then
    echo "   Warning: systemd-analyze verify reported problems:" >&2
    echo "$verify_out" | sed 's/^/     /' >&2
fi

echo ">> Installing $UNIT_PATH..."
install -m 0644 "$RENDERED" "$UNIT_PATH"
systemctl daemon-reload
systemctl enable "$SERVICE_NAME"

if [ "$START" -eq 1 ]; then
    echo ">> (Re)starting $SERVICE_NAME..."
    if ! systemctl restart "$SERVICE_NAME"; then
        journalctl -u "$SERVICE_NAME" -n 30 --no-pager >&2 || true
        die "$SERVICE_NAME failed to start (log above)"
    fi
    systemctl --no-pager status "$SERVICE_NAME" | head -n 5 || true
else
    echo ">> Enabled; it starts on the next boot (or: sudo systemctl start $SERVICE_NAME)"
fi

echo ">> Done. Logs: journalctl -u $SERVICE_NAME"
